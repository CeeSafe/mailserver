#!/usr/bin/env python3
"""Writes src/psl.cee from the Public Suffix List (https://publicsuffix.org/list/public_suffix_list.dat): every rule,
ICANN and private sections both (as OpenDMARC uses them), IDN labels in their A-label (xn--) form, sorted for binary
search. Run it now and then to pick up new suffixes; the output is checked in."""
import datetime, pathlib, urllib.request

URL = "https://publicsuffix.org/list/public_suffix_list.dat"
text = urllib.request.urlopen(URL).read().decode("utf-8")
rules = set()
for line in text.splitlines():
    line = line.strip()
    if not line or line.startswith("//"):
        continue
    rule = line.split()[0]
    labels = []
    for label in rule.split("."):
        prefix = ""
        if label.startswith("!"):
            prefix, label = "!", label[1:]
        if label != "*" and any(ord(c) > 127 for c in label):
            label = label.encode("idna").decode("ascii")
        labels.append(prefix + label.lower())
    rules.add(".".join(labels))
ordered = sorted(rules, key=lambda r: r.encode())
out = [f"// Generated by tools/psl.py from {URL} on {datetime.date.today()}: {len(ordered)} rules.",
       "", f"const PSL_COUNT: usize = {len(ordered)};", "", f"const PSL_RULES: [StringView; {len(ordered)}] = ["]
out += [f'    "{r}",' for r in ordered]
out += ["];", ""]
(pathlib.Path(__file__).resolve().parent.parent / "src" / "psl.cee").write_text("\n".join(out))
print(f"src/psl.cee: {len(ordered)} rules")
